#!/usr/bin/env python3
"""Generate the Homegrown brand assets from one geometry.

The mark is a four-bar waveform on a rounded tile: the same shape the Studio
favicon always used, now with a single source. Two colours only, both Studio
palette tokens: the tile is --bg-base and the bars are --accent-2 (the token
that means "audio"). No gradients, filters or glows, so it survives a 16px tab.

    python scripts/build/build_brand.py            # write every asset
    python scripts/build/build_brand.py --check    # fail if an asset is stale or missing

Writes
  apps/studio/public/favicon.svg, apple-touch-icon.png
  apps/marketing/favicon.svg, favicon.ico, apple-touch-icon.png, logo.svg
  desktop/assets/icon.ico        (the Windows executable icon, see launcher.spec)

SVGs are compared byte for byte by --check. PNG and ICO files are rasterised with
Pillow, whose output can differ between versions, so --check only verifies that
they exist and have the expected sizes. Re-run without --check after changing the
geometry below, and mirror the same bars into the two hand-kept inline copies
(apps/studio/src/components/brand/BrandMark.tsx and the header and footer marks in
apps/marketing/index.html).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]

TILE = "#14151a"  # --bg-base
BAR = "#1cc5e3"  # --accent-2
INK = "#f5f6f8"  # --text-primary

# 32 x 32 design grid: (x, y, width, height). Four bars, 4 wide: thinner bars
# turn to mush in a 16px tab.
BARS = [(5, 12, 4, 8), (12, 5, 4, 22), (19, 9, 4, 14), (26, 13, 4, 6)]
TILE_RADIUS = 7
BAR_RADIUS = 2

COMMENT = (
    "  <!-- Homegrown mark, generated by scripts/build/build_brand.py. Two colours:\n"
    "       --bg-base and --accent-2. Edit the generator, not this file.\n"
    "       NB: no double hyphens in this comment. XML forbids them. -->\n"
)


def bars_svg(indent: str = "    ") -> str:
    return "\n".join(
        f'{indent}<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{BAR_RADIUS}" />' for x, y, w, h in BARS
    )


def favicon_svg() -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">\n'
        + COMMENT
        + f'  <rect width="32" height="32" rx="{TILE_RADIUS}" fill="{TILE}" />\n'
        + f'  <g fill="{BAR}">\n{bars_svg()}\n  </g>\n</svg>\n'
    )


def logo_svg() -> str:
    """Horizontal lockup for dark surfaces: mark, then the tracked uppercase wordmark.

    The wordmark is live text, so it needs Archivo (the Studio and landing page both
    load it) and falls back to the system sans-serif when the file is opened alone.
    """
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 232 32" role="img" aria-label="Homegrown">\n'
        + COMMENT
        + f'  <rect width="32" height="32" rx="{TILE_RADIUS}" fill="{TILE}" />\n'
        + f'  <g fill="{BAR}">\n{bars_svg()}\n  </g>\n'
        + f'  <text x="44" y="22.5" fill="{INK}" font-family="Archivo, \'Archivo Variable\', system-ui, sans-serif" '
        + 'font-size="17" font-weight="650" letter-spacing="3.2">HOMEGROWN</text>\n</svg>\n'
    )


def render_png(size: int) -> Image.Image:
    """Rasterise the tile at `size` px, supersampled 16x then downscaled."""
    scale = 16
    big = size * scale
    k = big / 32
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((0, 0, big - 1, big - 1), radius=TILE_RADIUS * k, fill=TILE)
    for x, y, w, h in BARS:
        d.rounded_rectangle((x * k, y * k, (x + w) * k - 1, (y + h) * k - 1), radius=BAR_RADIUS * k, fill=BAR)
    return img.resize((size, size), Image.LANCZOS)


def write_ico(path: Path, sizes: list[int]) -> None:
    base = render_png(max(sizes))
    base.save(path, format="ICO", sizes=[(s, s) for s in sizes])


def ico_sizes(path: Path) -> set[int]:
    with Image.open(path) as im:
        return {w for w, _h in im.info.get("sizes", set()) or {im.size}}


TEXT_ASSETS = {
    ROOT / "apps" / "studio" / "public" / "favicon.svg": favicon_svg,
    ROOT / "apps" / "marketing" / "favicon.svg": favicon_svg,
    ROOT / "apps" / "marketing" / "logo.svg": logo_svg,
}
PNG_ASSETS = {
    ROOT / "apps" / "studio" / "public" / "apple-touch-icon.png": 180,
    ROOT / "apps" / "marketing" / "apple-touch-icon.png": 180,
}
ICO_ASSETS = {
    ROOT / "apps" / "marketing" / "favicon.ico": [16, 32, 48],
    ROOT / "desktop" / "assets" / "icon.ico": [16, 24, 32, 48, 64, 128, 256],
}


def generate() -> None:
    for path, fn in TEXT_ASSETS.items():
        path.write_text(fn(), encoding="utf-8", newline="\n")
    for path, size in PNG_ASSETS.items():
        render_png(size).save(path, format="PNG", optimize=True)
    for path, sizes in ICO_ASSETS.items():
        write_ico(path, sizes)


def check() -> list[str]:
    problems: list[str] = []
    for path, fn in TEXT_ASSETS.items():
        if not path.exists():
            problems.append(f"missing {path.relative_to(ROOT)}")
        elif path.read_text(encoding="utf-8") != fn():
            problems.append(f"stale {path.relative_to(ROOT)}")
    for path, size in PNG_ASSETS.items():
        if not path.exists():
            problems.append(f"missing {path.relative_to(ROOT)}")
            continue
        with Image.open(path) as im:
            if im.size != (size, size):
                problems.append(f"wrong size {path.relative_to(ROOT)}: {im.size}")
    for path, sizes in ICO_ASSETS.items():
        if not path.exists():
            problems.append(f"missing {path.relative_to(ROOT)}")
        elif ico_sizes(path) != set(sizes):
            problems.append(f"wrong sizes {path.relative_to(ROOT)}: {sorted(ico_sizes(path))}")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if an asset is stale or missing")
    args = ap.parse_args()
    if args.check:
        problems = check()
        if problems:
            print("Brand assets are out of date:\n  " + "\n  ".join(problems))
            print("Run: python scripts/build/build_brand.py")
            return 1
        print("OK: brand assets match scripts/build/build_brand.py.")
        return 0
    generate()
    print("Wrote brand assets:")
    for path in [*TEXT_ASSETS, *PNG_ASSETS, *ICO_ASSETS]:
        print("  " + str(path.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
