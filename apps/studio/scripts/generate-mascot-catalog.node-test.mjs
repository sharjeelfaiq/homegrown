import assert from 'node:assert/strict'
import { mkdtemp, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import test from 'node:test'
import { buildMascotCatalog, generateMascotCatalog } from './generate-mascot-catalog.mjs'

test('sorts numeric IDs and allows gaps', () => {
  assert.deepEqual(buildMascotCatalog(['10b.webp', '2a.webp', '10a.webp', '2b.webp', '4b.webp', '4a.webp']), [
    { id: 2, label: 'Mascot 2', directions: '/mascots/2a.webp', reactions: '/mascots/2b.webp' },
    { id: 4, label: 'Mascot 4', directions: '/mascots/4a.webp', reactions: '/mascots/4b.webp' },
    { id: 10, label: 'Mascot 10', directions: '/mascots/10a.webp', reactions: '/mascots/10b.webp' },
  ])
})

test('rejects malformed webp filenames', () => {
  assert.throws(() => buildMascotCatalog(['cat-directions.webp']), /Malformed mascot/)
})

test('rejects duplicate numeric IDs including zero-padded variants', () => {
  assert.throws(() => buildMascotCatalog(['1a.webp', '01b.webp']), /Duplicate mascot numeric ID/)
})

test('rejects incomplete mascot pairs and an empty catalog', () => {
  assert.throws(() => buildMascotCatalog(['5a.webp']), /missing: 5b\.webp/)
  assert.throws(() => buildMascotCatalog([]), /catalog is empty/)
})

test('writes a typed generated catalog module', async () => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'mascot-catalog-'))
  const mascotDirectory = path.join(directory, 'mascots')
  const outputFile = path.join(directory, 'mascotCatalog.ts')
  await (await import('node:fs/promises')).mkdir(mascotDirectory)
  await Promise.all(['3a.webp', '3b.webp'].map((file) => writeFile(path.join(mascotDirectory, file), 'sheet')))

  await generateMascotCatalog({ mascotDirectory, outputFile })
  const generated = await (await import('node:fs/promises')).readFile(outputFile, 'utf8')
  assert.match(generated, /generated by scripts\/generate-mascot-catalog\.mjs/)
  assert.match(generated, /export type StudioMascot/)
  assert.match(generated, /"directions": "\/mascots\/3a\.webp"/)
})
