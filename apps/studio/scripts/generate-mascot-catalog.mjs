import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const FILE_PATTERN = /^(\d+)([ab])\.webp$/

/**
 * Turn top-level mascot filenames into the Studio's source-controlled catalog.
 * `a` sheets contain directions and `b` sheets contain reactions.
 */
export function buildMascotCatalog(fileNames) {
  const malformed = fileNames.filter((fileName) => fileName.endsWith('.webp') && !FILE_PATTERN.test(fileName))
  if (malformed.length > 0) {
    throw new Error(`Malformed mascot .webp filename(s): ${malformed.sort().join(', ')}. Expected <positive-number>a.webp or <positive-number>b.webp.`)
  }

  /** @type {Map<number, { rawIds: Set<string>, a?: string, b?: string }>} */
  const byId = new Map()
  for (const fileName of fileNames) {
    const match = FILE_PATTERN.exec(fileName)
    if (!match) continue

    const [, rawId, sheet] = match
    const id = Number(rawId)
    if (!Number.isSafeInteger(id) || id <= 0) {
      throw new Error(`Mascot ID in ${fileName} must be a positive safe integer.`)
    }

    const entry = byId.get(id) ?? { rawIds: new Set() }
    entry.rawIds.add(rawId)
    if (entry[sheet]) {
      throw new Error(`Duplicate mascot ${sheet} sheet for numeric ID ${id}: ${entry[sheet]} and ${fileName}.`)
    }
    entry[sheet] = fileName
    byId.set(id, entry)
  }

  if (byId.size === 0) {
    throw new Error('Mascot catalog is empty. Add at least one <positive-number>a.webp / <positive-number>b.webp pair.')
  }

  const ambiguous = [...byId.entries()].filter(([, entry]) => entry.rawIds.size > 1)
  if (ambiguous.length > 0) {
    const details = ambiguous
      .map(([id, entry]) => `${[...entry.rawIds].sort().join(' and ')} (numeric ID ${id})`)
      .join(', ')
    throw new Error(`Duplicate mascot numeric ID(s), including ambiguous zero-padded forms: ${details}.`)
  }

  const missingPartners = [...byId.entries()]
    .filter(([, entry]) => !entry.a || !entry.b)
    .map(([id, entry]) => `${id}${entry.a ? 'b' : 'a'}.webp`)
  if (missingPartners.length > 0) {
    throw new Error(`Mascot pair is incomplete; missing: ${missingPartners.join(', ')}.`)
  }

  return [...byId.entries()]
    .sort(([left], [right]) => left - right)
    .map(([id, entry]) => ({
      id,
      label: `Mascot ${id}`,
      directions: `/mascots/${entry.a}`,
      reactions: `/mascots/${entry.b}`,
    }))
}

export function renderMascotCatalog(catalog) {
  return `// This file is generated by scripts/generate-mascot-catalog.mjs. Do not edit it by hand.\n\nexport type StudioMascot = {\n  readonly id: number\n  readonly label: string\n  readonly directions: string\n  readonly reactions: string\n}\n\nexport const MASCOTS: readonly StudioMascot[] = ${JSON.stringify(catalog, null, 2)}\n\nexport const DEFAULT_MASCOT_ID = 2\n`
}

export async function generateMascotCatalog({ mascotDirectory, outputFile }) {
  const entries = await readdir(mascotDirectory, { withFileTypes: true })
  const catalog = buildMascotCatalog(entries.filter((entry) => entry.isFile()).map((entry) => entry.name))
  await writeFile(outputFile, renderMascotCatalog(catalog), 'utf8')
  return catalog
}

async function main() {
  const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
  const studioDirectory = path.resolve(scriptDirectory, '..')
  const catalog = await generateMascotCatalog({
    mascotDirectory: path.join(studioDirectory, 'public', 'mascots'),
    outputFile: path.join(studioDirectory, 'src', 'generated', 'mascotCatalog.ts'),
  })
  console.log(`Generated mascot catalog with ${catalog.length} mascot${catalog.length === 1 ? '' : 's'}.`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(`Mascot catalog generation failed: ${error.message}`)
    process.exitCode = 1
  })
}
